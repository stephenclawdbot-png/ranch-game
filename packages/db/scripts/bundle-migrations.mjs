#!/usr/bin/env node
// Embeds migrations/*.sql (+ the drizzle journal) into src/migrations.generated.ts so the
// runtime migrator needs no filesystem access (works inside Next.js / Vercel bundles).
// Run automatically by `pnpm --filter @thoroughbred/db generate`. A test asserts the bundle
// is in sync with the migrations folder.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "migrations/meta/_journal.json"), "utf8"));
const entries = journal.entries.map((e) => {
  const sql = readFileSync(join(root, "migrations", `${e.tag}.sql`), "utf8");
  return { tag: e.tag, when: e.when, hash: createHash("sha256").update(sql).digest("hex"), sql };
});
const body =
  "// GENERATED by scripts/bundle-migrations.mjs from migrations/. Do not edit.\n" +
  "export interface BundledMigration { tag: string; when: number; hash: string; sql: string }\n\n" +
  `export const MIGRATIONS: readonly BundledMigration[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(join(root, "src/migrations.generated.ts"), body);
console.log(`bundled ${entries.length} migrations`);
