/** Markdown table helpers and result-file writing (docs/economy/results/). */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = resolve(HERE, "../../..");
export const RESULTS_DIR = resolve(REPO_ROOT, "docs/economy/results");

export type Cell = string | number;

export function fmt(n: number, digits = 0): string {
  if (!Number.isFinite(n)) return "n/a";
  return n.toLocaleString("en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

export function usd(n: number, digits = 2): string {
  const s = fmt(Math.abs(n), digits);
  return n < 0 ? `-$${s}` : `$${s}`;
}

export function pct(x: number, digits = 1): string {
  return `${fmt(x * 100, digits)}%`;
}

export function table(headers: readonly string[], rows: readonly (readonly Cell[])[]): string {
  const line = (cells: readonly Cell[]) => `| ${cells.map((c) => String(c)).join(" | ")} |`;
  return [line(headers), `|${headers.map(() => "---").join("|")}|`, ...rows.map(line)].join("\n");
}

export class Report {
  private parts: string[] = [];
  constructor(
    public readonly name: string,
    title: string,
    intro?: string,
  ) {
    this.parts.push(`# ${title}`, "");
    this.parts.push(`_Generated by \`tools/economy-sim\` (\`${name}\`). Do not edit by hand; rerun the sim._`, "");
    if (intro) this.parts.push(intro, "");
  }
  h2(t: string): this {
    this.parts.push(`## ${t}`, "");
    return this;
  }
  p(t: string): this {
    this.parts.push(t, "");
    return this;
  }
  table(headers: readonly string[], rows: readonly (readonly Cell[])[]): this {
    this.parts.push(table(headers, rows), "");
    return this;
  }
  toString(): string {
    return this.parts.join("\n");
  }
  write(dir = RESULTS_DIR): string {
    mkdirSync(dir, { recursive: true });
    const path = resolve(dir, `${this.name}.md`);
    writeFileSync(path, this.toString());
    return path;
  }
}
